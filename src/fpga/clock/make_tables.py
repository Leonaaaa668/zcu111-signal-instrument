"""Generate an exact 2400 MHz LMX2594 plan from the Xilinx 409.6 MHz plan.

Register fields: TI SNAS696C sections 7.6.2, 7.6.5 and 7.6.10.
The unchanged analog/board settings retain the vendor template's values.
This is a calculated configuration, NOT a board-measured jitter/lock result.
"""
from fractions import Fraction
from pathlib import Path
import hashlib
import re

ROOT = Path(__file__).resolve().parent


def read_words(path):
    return [int(x, 16) for x in re.findall(r"0x[0-9A-Fa-f]+", path.read_text())]


def make_plan():
    template = ROOT / "vendor" / "LMX2594_409.6.txt"
    words = read_words(template)
    assert len(words) == 113
    assert [w >> 16 for w in words] == list(range(112, -1, -1))
    regs = {w >> 16: w & 0xFFFF for w in words}
    assert regs[9] == 0x0604 and regs[10] == 0x10D8
    assert regs[11] == 0x0018 and regs[12] == 0x5001
    assert regs[36] == 80 and regs[75] == 0x0980
    assert (regs[44] & 0xE0) == 0x20  # A/B enabled; MASH not reset
    assert ((regs[45] >> 11) & 3) == 0  # OUTA = divided VCO
    assert (regs[46] & 3) == 0           # OUTB = divided VCO (ADC tile1)
    regs.update({34: 0, 36: 78, 38: 0, 39: 8, 42: 0, 43: 1,
                 75: (regs[75] & ~0x7C0) | (1 << 6)})  # /4
    # PFD=122.88 MHz, VCO=9600 MHz, third-order fractional modulator.
    assert ((regs[37] >> 8) & 0x3F) == 3 and (regs[44] & 7) == 3
    n = ((regs[34] & 7) << 16) | regs[36]
    den = (regs[38] << 16) | regs[39]
    num = (regs[42] << 16) | regs[43]
    vco = Fraction(122880000) * (n + Fraction(num, den))
    assert vco == 9600000000 and vco / 4 == 2400000000
    final = [(addr << 16) | regs[addr] for addr in range(112, -1, -1)]
    (ROOT / "LMX2594_2400.0.txt").write_text(
        "".join(f"R{w >> 16}\t0x{w:06X}\n" for w in final), encoding="ascii")
    lmk = read_words(ROOT / "vendor" / "LMK04208_122.88.txt")
    assert len(lmk) == 26
    header = "/* Generated by clock/make_tables.py; vendor notices in clock/vendor/LICENSE. */\n"
    for name, values in [("adc3_lmk_12288", lmk), ("adc3_lmx_2400", final)]:
        header += f"static const unsigned int {name}[{len(values)}] = {{\n"
        header += "".join(f"    0x{v:08X}u,\n" for v in values) + "};\n"
    (ROOT / "clock_tables.h").write_text(header, encoding="ascii")
    report = ("CALCULATED_CLOCK_PLAN_PASS\nReference = 122880000 Hz\n"
              "N = 78 + 1/8; channel divider = 4\nVCO = 9600000000 Hz\n"
              "OUTA = OUTB = 2400000000 Hz (nominal, reference accuracy applies)\n"
              f"Vendor LMX template SHA256 = {hashlib.sha256(template.read_bytes()).hexdigest()}\n"
              "Physical PLL lock, amplitude and jitter: NOT TESTED\n")
    (ROOT / "clock_plan_report.txt").write_text(report, encoding="ascii")
    print(report)
    return final


if __name__ == "__main__":
    make_plan()
